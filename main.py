def theme_id(t_idx, s_idx): return t_idx * len(STYLES) + s_idx
def theme_from_id(tid): return TOPICS[tid // len(STYLES)], STYLES[tid % len(STYLES)]
def theme_name(tid):
    topic, style = theme_from_id(tid)
    return f"{topic['emoji']} {topic['name']} · {style[0]}"

