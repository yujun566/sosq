async def decorate_server(interaction: discord.Interaction, 주제: str):
    if 주제 == "-1" or not 주제.isdigit() or int(주제) not in allowed_themes(interaction.user.id, "server"):
        return await interaction.response.send_message(
            "🔒 이 테마를 사용할 수 있는 **라이센스가 없어요!**\n> `/라이센스등록` 으로 키를 먼저 등록해줘요 🔑", ephemeral=True)
