async def ac_theme_all(interaction: discord.Interaction, current: str):
    """라이센스 생성용: 전체 + 200테마"""
    choices = [app_commands.Choice(name="🌐 전체 테마 (올패스)", value="all")]
    for tid in range(TOTAL_THEMES):
        n = theme_name(tid)
        if current.lower() in n.lower():
            choices.append(app_commands.Choice(name=n, value=str(tid)))
        if len(choices) >= 25:
            break
    return choices

def make_ac_licensed(lic_type):
    async def ac(interaction: discord.Interaction, current: str):
        ids = allowed_themes(interaction.user.id, lic_type)
        out = []
        for tid in ids:
            n = theme_name(tid)
            if current.lower() in n.lower():
                out.append(app_commands.Choice(name=n, value=str(tid)))
            if len(out) >= 25:
                break
        if not out:
            out.append(app_commands.Choice(name="🔒 등록된 라이센스가 없어요!", value="-1"))
        return out
    return ac

